// Package k8scloudinit renders the cloud-init user-data a Kumo Kubernetes node
// boots from: the control plane's, which hands kubeadm the PKI kumod generated
// and applies the add-ons the image carries, and a worker's, which joins with a
// bootstrap token and pins the cluster CA by hash
// (docs/design/08-kubernetes.md sections 4 and 5).
//
// Like internal/service/dbcloudinit it is free of libvirt, of the database and
// of the services, so every rule is a function with a test. Everything that
// goes into a configuration file is marshaled as YAML from structs rather than
// templated, and the scripts interpolate nothing a request supplies: they read
// the files.
package k8scloudinit

import (
	"errors"
	"fmt"
	"net/netip"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/ahmedmohamedut/kumo/internal/service/k8spki"
)

const cloudConfigHeader = "#cloud-config"

// Paths on a node.
const (
	// runDir holds the kubeadm configuration and the script. /run, so the
	// bootstrap token in the configuration never lands on a disk, and the
	// script is invoked as `bash <path>` because /run is noexec.
	runDir     = "/run/kumo-k8s"
	scriptPath = runDir + "/firstboot.sh"
	configPath = runDir + "/kubeadm.yaml"
	rbacPath   = runDir + "/rbac.yaml"
	// manifestDir is where the image keeps the add-on manifests
	// (packaging/images/kubernetes-1.37).
	manifestDir = "/usr/share/kumo/kubernetes"
	pkiDir      = "/etc/kubernetes/pki"
	// criSocket is CRI-O's, which the image runs.
	criSocket = "unix:///var/run/crio/crio.sock"
	// kubeadmAPI is the kubeadm configuration version 1.37 reads.
	kubeadmAPI = "kubeadm.k8s.io/v1beta4"
	// versionPlaceholder is replaced at boot with the node's own kubeadm
	// version, so a seed never names a Kubernetes version the image does not
	// carry -- which would make kubeadm pull, and nodes have no registry.
	versionPlaceholder = "@KUBERNETES_VERSION@"
	// APIPort is the API server's port.
	APIPort = 6443
)

// Console markers, which say where a node's first boot got to. kumod does not
// read them; they are for whoever reads the serial log a create failed with.
const (
	markerControlPlaneReady = "KUMO-K8S-CONTROL-PLANE-READY"
	markerJoined            = "KUMO-K8S-JOINED"
	markerFailed            = "KUMO-K8S-FIRSTBOOT-FAILED"
)

// MaxNameLength bounds a cluster or node name: both are DNS labels.
const MaxNameLength = 63

var (
	labelPattern  = regexp.MustCompile(`^[a-z]([a-z0-9-]*[a-z0-9])?$`)
	caHashPattern = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)
)

// ErrInvalidRequest means a field could not be rendered safely.
var ErrInvalidRequest = errors.New("k8scloudinit: the request is not renderable")

// ControlPlaneRequest is everything a control plane's first boot needs.
type ControlPlaneRequest struct {
	// ClusterName is the cluster's name, a DNS label.
	ClusterName string
	// NodeName is the node's hostname and Kubernetes node name.
	NodeName string
	// Endpoint is the API server's DNS name, api.<cluster>.<vpc> (K6). It is
	// the certificate's SAN and every kubeconfig's server.
	Endpoint string
	// NodeIP is the address the VM was reserved, which the API server
	// advertises and kubelet registers with.
	NodeIP string
	// PodCIDR and ServiceCIDR are the cluster's ranges (K9).
	PodCIDR     string
	ServiceCIDR string
	// Token is the bootstrap token the workers join with.
	Token k8spki.BootstrapToken
	// PKI is the cluster's, generated by kumod.
	PKI *k8spki.ClusterPKI
}

// WorkerRequest is everything a worker's first boot needs. It carries no key:
// a worker's seed holds an expiring token and the CA's hash, nothing it could
// be made to impersonate the control plane with.
type WorkerRequest struct {
	NodeName string
	Endpoint string
	// ControlPlaneIP is where Endpoint points, written into /etc/hosts so the
	// join does not wait on the VPC's DNS.
	ControlPlaneIP string
	NodeIP         string
	Token          k8spki.BootstrapToken
	// CAHash pins the cluster CA (k8spki.CAHash).
	CAHash string
}

// ValidateControlPlane reports whether the request can be rendered.
func ValidateControlPlane(req ControlPlaneRequest) error {
	if err := validateLabel("cluster name", req.ClusterName); err != nil {
		return err
	}
	if err := validateLabel("node name", req.NodeName); err != nil {
		return err
	}
	if err := validateEndpoint(req.Endpoint); err != nil {
		return err
	}
	node, err := parseIPv4("node ip", req.NodeIP)
	if err != nil {
		return err
	}
	pods, err := parsePrefix("pod cidr", req.PodCIDR)
	if err != nil {
		return err
	}
	services, err := parsePrefix("service cidr", req.ServiceCIDR)
	if err != nil {
		return err
	}
	if pods.Overlaps(services) {
		return fmt.Errorf("%w: pod cidr %s overlaps service cidr %s", ErrInvalidRequest, pods, services)
	}
	for name, prefix := range map[string]netip.Prefix{"pod cidr": pods, "service cidr": services} {
		if prefix.Contains(node) {
			return fmt.Errorf("%w: %s %s contains the node's address", ErrInvalidRequest, name, prefix)
		}
	}
	if err := req.Token.Validate(); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalidRequest, err)
	}
	if err := req.PKI.Validate(); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalidRequest, err)
	}
	return nil
}

// ValidateWorker reports whether the request can be rendered.
func ValidateWorker(req WorkerRequest) error {
	if err := validateLabel("node name", req.NodeName); err != nil {
		return err
	}
	if err := validateEndpoint(req.Endpoint); err != nil {
		return err
	}
	if _, err := parseIPv4("control plane ip", req.ControlPlaneIP); err != nil {
		return err
	}
	if _, err := parseIPv4("node ip", req.NodeIP); err != nil {
		return err
	}
	if err := req.Token.Validate(); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalidRequest, err)
	}
	if !caHashPattern.MatchString(req.CAHash) {
		return fmt.Errorf("%w: ca hash %q", ErrInvalidRequest, req.CAHash)
	}
	return nil
}

func validateLabel(field, v string) error {
	if v == "" || len(v) > MaxNameLength || !labelPattern.MatchString(v) || strings.Contains(v, "--") {
		return fmt.Errorf("%w: %s %q is not a DNS label", ErrInvalidRequest, field, v)
	}
	return nil
}

// validateEndpoint accepts a DNS name of at least two labels, the shape of
// api.<cluster>.<vpc>.
func validateEndpoint(v string) error {
	labels := strings.Split(v, ".")
	if len(v) > 253 || len(labels) < 2 {
		return fmt.Errorf("%w: endpoint %q is not a DNS name", ErrInvalidRequest, v)
	}
	for _, l := range labels {
		if err := validateLabel("endpoint label", l); err != nil {
			return fmt.Errorf("%w: endpoint %q is not a DNS name", ErrInvalidRequest, v)
		}
	}
	return nil
}

func parseIPv4(field, v string) (netip.Addr, error) {
	addr, err := netip.ParseAddr(v)
	if err != nil || !addr.Is4() {
		return netip.Addr{}, fmt.Errorf("%w: %s %q is not an IPv4 address", ErrInvalidRequest, field, v)
	}
	return addr, nil
}

func parsePrefix(field, v string) (netip.Prefix, error) {
	prefix, err := netip.ParsePrefix(v)
	if err != nil || !prefix.Addr().Is4() || prefix != prefix.Masked() {
		return netip.Prefix{}, fmt.Errorf("%w: %s %q is not an IPv4 network", ErrInvalidRequest, field, v)
	}
	return prefix, nil
}

// document is the cloud-config this package renders.
type document struct {
	// A node is not a machine anyone has a shell on: no key pair, no
	// password login.
	SSHPwauth bool   `yaml:"ssh_pwauth"`
	Hostname  string `yaml:"hostname"`
	// manage_etc_hosts is off, so cloud-init does not replace the entry
	// below on a later boot.
	ManageEtcHosts bool        `yaml:"manage_etc_hosts"`
	WriteFiles     []writeFile `yaml:"write_files"`
	Runcmd         [][]string  `yaml:"runcmd"`
}

type writeFile struct {
	Path        string `yaml:"path"`
	Permissions string `yaml:"permissions"`
	Content     string `yaml:"content"`
	Append      bool   `yaml:"append,omitempty"`
}

// ControlPlaneUserData renders a control plane's seed.
//
// It carries the cluster's CA keys, written where kubeadm looks for them, and
// is the one seed that does: the control plane's /etc/kubernetes/pki holds the
// same keys by design, and the seed disk stays attached to the domain as long
// as the VM exists (docs/design/08-kubernetes.md section 5).
func ControlPlaneUserData(req ControlPlaneRequest) (string, error) {
	if err := ValidateControlPlane(req); err != nil {
		return "", err
	}

	config, err := marshalAll(
		initConfiguration{
			APIVersion: kubeadmAPI,
			Kind:       "InitConfiguration",
			BootstrapTokens: []bootstrapToken{{
				Token: req.Token.Value(),
				// Long enough for the workers of a create, which boot once
				// the API answers; a scale-up mints its own (section 4).
				TTL:    "1h0m0s",
				Groups: []string{"system:bootstrappers:kubeadm:default-node-token"},
				Usages: []string{"signing", "authentication"},
			}},
			LocalAPIEndpoint: apiEndpoint{AdvertiseAddress: req.NodeIP, BindPort: APIPort},
			NodeRegistration: nodeRegistration(req.NodeName, req.NodeIP),
		},
		clusterConfiguration{
			APIVersion:           kubeadmAPI,
			Kind:                 "ClusterConfiguration",
			ClusterName:          req.ClusterName,
			KubernetesVersion:    versionPlaceholder,
			ControlPlaneEndpoint: fmt.Sprintf("%s:%d", req.Endpoint, APIPort),
			EncryptionAlgorithm:  "ECDSA-P256",
			APIServer:            apiServer{CertSANs: []string{req.Endpoint}},
			Networking: networking{
				PodSubnet:     req.PodCIDR,
				ServiceSubnet: req.ServiceCIDR,
				DNSDomain:     "cluster.local",
			},
		},
	)
	if err != nil {
		return "", err
	}

	p := req.PKI
	files := []writeFile{
		hostsEntry(req.NodeIP, req.Endpoint),
		{Path: pkiDir + "/ca.crt", Permissions: "0644", Content: string(p.CA.CertPEM)},
		{Path: pkiDir + "/ca.key", Permissions: "0600", Content: string(p.CA.KeyPEM.Bytes())},
		{Path: pkiDir + "/front-proxy-ca.crt", Permissions: "0644", Content: string(p.FrontProxyCA.CertPEM)},
		{Path: pkiDir + "/front-proxy-ca.key", Permissions: "0600", Content: string(p.FrontProxyCA.KeyPEM.Bytes())},
		{Path: pkiDir + "/etcd/ca.crt", Permissions: "0644", Content: string(p.EtcdCA.CertPEM)},
		{Path: pkiDir + "/etcd/ca.key", Permissions: "0600", Content: string(p.EtcdCA.KeyPEM.Bytes())},
		{Path: pkiDir + "/sa.key", Permissions: "0600", Content: string(p.ServiceAccountKey.Bytes())},
		{Path: pkiDir + "/sa.pub", Permissions: "0644", Content: string(p.ServiceAccountPub)},
		{Path: configPath, Permissions: "0600", Content: config},
		{Path: rbacPath, Permissions: "0644", Content: rbacManifest},
		{Path: scriptPath, Permissions: "0700", Content: controlPlaneScript},
	}
	return render(req.NodeName, files)
}

// WorkerUserData renders a worker's seed.
func WorkerUserData(req WorkerRequest) (string, error) {
	if err := ValidateWorker(req); err != nil {
		return "", err
	}

	config, err := marshalAll(joinConfiguration{
		APIVersion: kubeadmAPI,
		Kind:       "JoinConfiguration",
		Discovery: discovery{BootstrapToken: discoveryToken{
			APIServerEndpoint: fmt.Sprintf("%s:%d", req.Endpoint, APIPort),
			Token:             req.Token.Value(),
			CACertHashes:      []string{req.CAHash},
		}},
		NodeRegistration: nodeRegistration(req.NodeName, req.NodeIP),
	})
	if err != nil {
		return "", err
	}

	return render(req.NodeName, []writeFile{
		hostsEntry(req.ControlPlaneIP, req.Endpoint),
		{Path: configPath, Permissions: "0600", Content: config},
		{Path: scriptPath, Permissions: "0700", Content: workerScript},
	})
}

// hostsEntry points the endpoint at the control plane on the node itself. The
// VPC's dnsmasq serves the same name; this keeps a first boot from waiting on
// it, and keeps the control plane able to reach its own endpoint before
// anything else is up.
func hostsEntry(ip, endpoint string) writeFile {
	return writeFile{Path: "/etc/hosts", Permissions: "0644", Content: ip + " " + endpoint + "\n", Append: true}
}

func render(hostname string, files []writeFile) (string, error) {
	body, err := yaml.Marshal(document{
		SSHPwauth:      false,
		Hostname:       hostname,
		ManageEtcHosts: false,
		WriteFiles:     files,
		Runcmd:         [][]string{{"bash", scriptPath}},
	})
	if err != nil {
		return "", fmt.Errorf("k8scloudinit: marshal the cloud-config: %w", err)
	}
	return cloudConfigHeader + "\n" + string(body), nil
}

// marshalAll writes several documents as one multi-document YAML file, the
// form kubeadm's --config reads.
func marshalAll(docs ...any) (string, error) {
	parts := make([]string, 0, len(docs))
	for _, d := range docs {
		b, err := yaml.Marshal(d)
		if err != nil {
			return "", fmt.Errorf("k8scloudinit: marshal the kubeadm configuration: %w", err)
		}
		parts = append(parts, string(b))
	}
	return strings.Join(parts, "---\n"), nil
}

func nodeRegistration(name, ip string) registration {
	return registration{
		Name:      name,
		CRISocket: criSocket,
		// Explicit, so kubelet registers the VPC address whatever other
		// interface a node may have.
		KubeletExtraArgs: []arg{{Name: "node-ip", Value: ip}},
	}
}

// The subset of kubeadm's v1beta4 configuration Kumo sets. Anything left out
// is kubeadm's default.
type initConfiguration struct {
	APIVersion       string           `yaml:"apiVersion"`
	Kind             string           `yaml:"kind"`
	BootstrapTokens  []bootstrapToken `yaml:"bootstrapTokens"`
	LocalAPIEndpoint apiEndpoint      `yaml:"localAPIEndpoint"`
	NodeRegistration registration     `yaml:"nodeRegistration"`
}

type bootstrapToken struct {
	Token  string   `yaml:"token"`
	TTL    string   `yaml:"ttl"`
	Groups []string `yaml:"groups"`
	Usages []string `yaml:"usages"`
}

type apiEndpoint struct {
	AdvertiseAddress string `yaml:"advertiseAddress"`
	BindPort         int    `yaml:"bindPort"`
}

type registration struct {
	Name             string `yaml:"name"`
	CRISocket        string `yaml:"criSocket"`
	KubeletExtraArgs []arg  `yaml:"kubeletExtraArgs"`
}

type arg struct {
	Name  string `yaml:"name"`
	Value string `yaml:"value"`
}

type clusterConfiguration struct {
	APIVersion           string     `yaml:"apiVersion"`
	Kind                 string     `yaml:"kind"`
	ClusterName          string     `yaml:"clusterName"`
	KubernetesVersion    string     `yaml:"kubernetesVersion"`
	ControlPlaneEndpoint string     `yaml:"controlPlaneEndpoint"`
	EncryptionAlgorithm  string     `yaml:"encryptionAlgorithm"`
	APIServer            apiServer  `yaml:"apiServer"`
	Networking           networking `yaml:"networking"`
}

type apiServer struct {
	CertSANs []string `yaml:"certSANs"`
}

type networking struct {
	PodSubnet     string `yaml:"podSubnet"`
	ServiceSubnet string `yaml:"serviceSubnet"`
	DNSDomain     string `yaml:"dnsDomain"`
}

type joinConfiguration struct {
	APIVersion       string       `yaml:"apiVersion"`
	Kind             string       `yaml:"kind"`
	Discovery        discovery    `yaml:"discovery"`
	NodeRegistration registration `yaml:"nodeRegistration"`
}

type discovery struct {
	BootstrapToken discoveryToken `yaml:"bootstrapToken"`
}

type discoveryToken struct {
	APIServerEndpoint string   `yaml:"apiServerEndpoint"`
	Token             string   `yaml:"token"`
	CACertHashes      []string `yaml:"caCertHashes"`
}
